"""Generate docs/reference/api.md and docs/reference/settings.md.

Run from the repository root:  python scripts/generate_reference_docs.py
The API page is built from the public contract fixture and the live package;
the settings page from tess_core/config/config.yaml.example.
"""
from __future__ import annotations

import importlib
import inspect
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "tests" / "fixtures" / "public_api" / "contract.json"
KNOBS = ROOT / "tess_core" / "config" / "config.yaml.example"
OUT = ROOT / "docs" / "reference"

ENTRYPOINTS = [
    ("root", "tess_core", "The main entry point. Everything an embedding application needs."),
    ("shell", "tess_core.shell_surface", "Extra names for applications that build an interactive shell around the runtime."),
    ("platform", "tess_core.platform_support", "Operating-system support: the daemon, sandboxing and diagnostics."),
    ("testing", "tess_core.testing", "Internals exposed for integration tests. Not covered by the stability promise."),
]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


ALIASES = {
    "AnthropicBlock": "One content block of a message: text, an image, a tool call or a tool result.",
    "PermissionMode": "The permission modes: `default`, `acceptEdits`, `auto`, `dontAsk`, `bypassPermissions`.",
    "RuntimeSecretPurpose": "What a stored secret is for, such as a provider API key or an OAuth token.",
    "RuntimeSecretValue": "A secret given either as a literal value or as a `RuntimeSecretRef`.",
}


def _summary(obj: object) -> str:
    if inspect.isclass(obj) and "__doc__" not in vars(obj):
        return ""  # inherited docstrings (dict, tuple, Exception) say nothing about this name
    doc = getattr(obj, "__doc__", None) if (inspect.isclass(obj) or inspect.isroutine(obj)) else None
    if not doc:
        return ""
    first = inspect.cleandoc(doc).split("\n\n")[0].replace("\n", " ").strip()
    return first if len(first) <= 200 else first[:197].rstrip() + "..."


def _signature(name: str, obj: object) -> str:
    if inspect.isclass(obj):
        return f"class {name}"
    if inspect.isroutine(obj):
        prefix = "async def" if inspect.iscoroutinefunction(obj) else "def"
        try:
            sig = str(inspect.signature(obj))
        except (TypeError, ValueError):
            sig = "(...)"
        sig = sig.replace("'", "")
        if len(sig) > 110:
            sig = "(...)"
        return f"{prefix} {name}{sig}"
    return name if name in ALIASES else f"{name}: {type(obj).__name__}"


def build_api() -> str:
    contract = json.loads(CONTRACT.read_text())
    lines = [
        "# API reference",
        "",
        "<!-- Generated by scripts/generate_reference_docs.py. Do not edit by hand. -->",
        "",
        "The public surface of Tess Core. Names listed here are covered by the stability",
        "promise: they change only with a version bump and a note in the changelog. Anything",
        "you import from a deeper module path is internal and may change without notice.",
        "",
        "A test in the repository checks that every name on this page is importable from its",
        "entry point, and that nothing leaves the surface by accident.",
        "",
    ]
    root = importlib.import_module("tess_core")
    lines += ["## Start here", "", "The names most applications use. The guides explain each one.", "", "| Name | What it is |", "|---|---|"]
    for name, text in CORE:
        getattr(root, name)  # a renamed or removed name fails the build
        lines.append(f"| `{name}` | {_cell(text)} |")
    lines.append("")
    for key, module_name, blurb in ENTRYPOINTS:
        module = importlib.import_module(module_name)
        names = sorted(
            (n for n in contract["names"] if n["entrypoint"] == key and n.get("py") and n.get("status") == "active"),
            key=lambda n: (n["kind"], n["py"].lower()),
        )
        if not names:
            continue
        lines += [f"## `{module_name}`", "", blurb, ""]
        for kind, title in (("function", "Functions"), ("type", "Types"), ("constant", "Constants")):
            group = [n for n in names if n["kind"] == kind]
            if not group:
                continue
            lines += [f"### {title}", "", "| Name | Description |", "|---|---|"]
            for n in group:
                obj = getattr(module, n["py"])
                lines.append(f"| `{_cell(_signature(n['py'], obj))}` | {_cell(ALIASES.get(n['py']) or _summary(obj))} |")
            lines.append("")
        other = [n for n in names if n["kind"] not in {"function", "type", "constant"}]
        if other:
            lines += ["### Other", "", "| Name | Description |", "|---|---|"]
            for n in other:
                obj = getattr(module, n["py"])
                lines.append(f"| `{_cell(_signature(n['py'], obj))}` | {_cell(ALIASES.get(n['py']) or _summary(obj))} |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def build_settings() -> str:
    lines = [
        "# Settings reference",
        "",
        "<!-- Generated by scripts/generate_reference_docs.py. Do not edit by hand. -->",
        "",
        "Every runtime setting, with its default and allowed range. Set them under `knobs:` in",
        "`<runtime-home>/settings/config.yaml`, or override one with an environment variable:",
        "`TESS_CORE_<SECTION>_<NAME>`, for example `TESS_CORE_SUBAGENTS_MAX_LIVE=4`.",
        "",
        "See [Configuration](../configuration.md) for how the files fit together.",
        "",
    ]
    section = None
    comment: list[str] = []
    for raw in KNOBS.read_text().splitlines():
        if raw.startswith("#") or raw.strip() in {"", "knobs:"}:
            continue
        if re.match(r"^  [a-z_]+:\s*$", raw):
            section = raw.strip().rstrip(":")
            lines += ["", f"## `{section}`", "", "| Setting | Default | Range | Meaning |", "|---|---|---|---|"]
            continue
        stripped = raw.strip()
        if stripped.startswith("#"):
            comment.append(stripped.lstrip("# ").rstrip())
            continue
        if stripped.startswith("- "):
            lines[-1] = _append_list_item(lines[-1], stripped[2:].strip())
            continue
        name, _, value = stripped.partition(":")
        text = " ".join(comment)
        comment = []
        rng = ""
        match = re.search(r"\s*\[([^\]]+)\]\s*$", text)
        if match:
            rng, text = match.group(1), text[: match.start()].rstrip()
        value = value.strip()
        default = f"`{value}`" if value and value != "null" else ("unset" if value else "`[]`")
        lines.append(f"| `{section}.{name}` | {_cell(default)} | {_cell(rng)} | {_cell(text)} |")
    return "\n".join(lines).rstrip() + "\n"


def _append_list_item(row: str, item: str) -> str:
    cells = row.split(" | ")
    current = cells[1].strip("`")
    items = [] if current == "[]" else current.strip("[]").split(", ")
    cells[1] = "`[" + ", ".join([*items, item]) + "]`"
    return " | ".join(cells)


CORE = [
    ("start_runtime", "Start a runtime on a runtime home. The one call an embedding application needs first."),
    ("Runtime", "A started runtime: `sessions`, `scheduler`, `status()`, `inspect()`, `stop()`."),
    ("Session", "One open conversation: `run_turn`, `subscribe`, `cancel_turn`, `close`, `end`."),
    ("SessionOptions", "How a session is set up: provider, model, tools, permission mode, MCP servers, prompts."),
    ("Unavailable", "Returned by your `session_options` function when a session cannot be opened right now."),
    ("ToolDefinition", "A tool the model can call: name, description, input schema and an async handler."),
    ("ProviderRegistry", "A loaded provider registry. Pass one, or a path to its YAML file, to `start_runtime`."),
    ("ExecutionBudget", "A shared ceiling on model calls, tool calls and time across turns."),
    ("MonitorDeliveryController", "Lets a host claim, publish and settle monitor deliveries on its own channels."),
    ("SessionBusy", "Raised when a turn is started on a session that is already running one."),
    ("SessionEnded", "Raised when a session that has been ended is used again."),
    ("UnknownSessionError", "Raised when a session id does not exist in the runtime home."),
    ("RuntimeStopped", "Raised when a stopped runtime is used."),
]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "api.md").write_text(build_api())
    (OUT / "settings.md").write_text(build_settings())
    print("wrote", OUT / "api.md", "and", OUT / "settings.md")


if __name__ == "__main__":
    main()
